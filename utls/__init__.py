"""uTLS (Python): a Python port of refraction-networking/utls.

The library implements a TLS 1.3 / TLS 1.2 client whose ClientHello is fully
configurable, so that connections can mimic the fingerprints of Chrome,
Firefox, Safari, iOS, Android, Edge or custom clients.

Quick start::

    import utls

    conn = utls.connect("example.com", 443, preset=utls.HelloChrome_Auto)
    conn.sendall(b"GET / HTTP/1.1\\r\\nHost: example.com\\r\\nConnection: close\\r\\n\\r\\n")
    print(conn.recv(65536).decode("latin-1"))
    conn.close()
"""

